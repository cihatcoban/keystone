#!/usr/bin/env python3
"""Install Keystone into Cursor, opencode or GitHub Copilot.

Claude Code, Gemini CLI and Codex load Keystone as a plugin or extension
(docs/multi-agent-setup.md). These three read the shared Agent Skills
location instead, and this script puts Keystone there, plus the commands and
subagents each one supports:

| Harness  | Skills          | Commands                                       | Subagents                 |
|----------|-----------------|------------------------------------------------|---------------------------|
| cursor   | .agents/skills/ | — (skills are /-invocable)                     | —                         |
| opencode | .agents/skills/ | .opencode/commands/keystone-*.md               | .opencode/agents/         |
| copilot  | .agents/skills/ | .github/prompts/keystone-*.prompt.md (project) | .github/agents/ (project) |

    python3 install_agents.py opencode                 # this project
    python3 install_agents.py opencode --scope user    # every project
    python3 install_agents.py copilot --contract       # also AGENTS.md, if absent
    python3 install_agents.py cursor --uninstall
    python3 install_agents.py copilot --dry-run

Skills are symlinked so `git pull` in Keystone updates them (`--copy` to copy).

Ownership: a symlink into a Keystone `skills/` directory is Keystone's. A
generated file or a copied skill records a SHA-256 of what was written; it is
replaced or removed only while it still matches. Anything else — a file the
user wrote, or one of ours the user has since edited — is reported and left
alone.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import build_adapters  # noqa: E402 — must follow the sys.path insert; scripts/ is not a package

MARKER_PREFIX = (
    "<!-- GENERATED by Keystone scripts/install_agents.py; reinstall to update; sha256="
)
MARKER_LINE = re.compile(
    r"^<!-- GENERATED by Keystone scripts/install_agents\.py; reinstall to update; "
    r"sha256=([0-9a-f]{64}) -->\n",
    re.MULTILINE,
)
COPY_MARKER = ".keystone-installed"
HARNESSES = ("cursor", "opencode", "copilot")
PREAMBLE = (
    "This is a Keystone command. Activate every Keystone skill named below "
    "before acting, and follow the operating contract in AGENTS.md.\n\n"
)
COPILOT_ARGS = "${input:args}"
COPILOT_PREAMBLE = (
    f"`{COPILOT_ARGS}` below is whatever the user typed after the command; "
    "it may be empty.\n\n"
)

# Ownership states
ABSENT, CLEAN, MODIFIED, FOREIGN = "absent", "clean", "modified", "foreign"


def targets(harness: str, scope: str, root: Path) -> dict[str, Path | None]:
    home = Path.home()
    base = root if scope == "project" else home
    out: dict[str, Path | None] = {
        "skills": base / ".agents" / "skills",
        "commands": None,
        "agents": None,
    }
    if harness == "opencode":
        conf = (
            root / ".opencode" if scope == "project" else home / ".config" / "opencode"
        )
        out["commands"], out["agents"] = conf / "commands", conf / "agents"
    elif harness == "copilot" and scope == "project":
        out["commands"], out["agents"] = (
            root / ".github" / "prompts",
            root / ".github" / "agents",
        )
    return out


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def stamped(head: str, body: str) -> str:
    """head + a marker carrying the hash of head + body, then body."""
    digest = sha256((head + body).encode("utf-8"))
    return f"{head}{MARKER_PREFIX}{digest} -->\n{body}"


def adapt(body: str, arguments: str) -> str:
    text = body.replace("$ARGUMENTS", arguments).replace("`CLAUDE.md`", "`AGENTS.md`")
    return text.replace("${CLAUDE_PLUGIN_ROOT}", ROOT.as_posix())


def frontmatter(fields: dict[str, str]) -> str:
    # JSON strings are valid YAML scalars and survive ': ' inside a description.
    lines = [f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in fields.items()]
    return "---\n" + "\n".join(lines) + "\n---\n"


def agent_fields(text: str) -> tuple[dict[str, str], str]:
    """Frontmatter fields and body of an agents/*.md file."""
    if not text.startswith("---\n"):
        raise ValueError("no frontmatter")
    meta, sep, body = text[4:].partition("\n---\n")
    if not sep:
        raise ValueError("unterminated frontmatter")
    fields = {}
    for line in meta.splitlines():
        key, colon, value = line.partition(":")
        if colon and key.strip():
            fields[key.strip()] = value.strip()
    return fields, body.lstrip()


def rendered(harness: str) -> tuple[dict[str, str], dict[str, str]]:
    """({command file name: content}, {agent file name: content})."""
    commands, agents = {}, {}
    for src in sorted((ROOT / "commands").glob("*.md")):
        desc, body = build_adapters.parse_command(src)
        if harness == "opencode":
            commands[f"keystone-{src.stem}.md"] = stamped(
                frontmatter({"description": desc}),
                "\n" + PREAMBLE + adapt(body, "$ARGUMENTS"),
            )
        elif harness == "copilot":
            commands[f"keystone-{src.stem}.prompt.md"] = stamped(
                frontmatter({"description": desc}),
                "\n" + PREAMBLE + COPILOT_PREAMBLE + adapt(body, COPILOT_ARGS),
            )
    for src in sorted((ROOT / "agents").glob("*.md")):
        try:
            fields, body = agent_fields(src.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise SystemExit(f"{src}: {exc}") from exc
        if harness == "opencode":
            head = frontmatter(
                {"description": fields["description"], "mode": "subagent"}
            )
        elif harness == "copilot":
            head = frontmatter(
                {"name": fields["name"], "description": fields["description"]}
            )
        else:
            continue
        agents[src.name] = stamped(head, "\n" + body)
    return commands, agents


def link_is_ours(path: Path) -> bool:
    """A symlink to <a Keystone checkout>/skills/<same name>, even if it dangles."""
    try:
        target = Path(os.readlink(path))
    except OSError:
        return False
    if not target.is_absolute():
        target = path.parent / target
    if target.name != path.name or target.parent.name != "skills":
        return False
    if not target.exists():
        return True  # dangling: Keystone was moved or deleted; removing loses nothing
    checkout = target.parent.parent
    try:
        manifest = json.loads(
            (checkout / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8")
        )
    except (OSError, ValueError):
        return False
    return manifest.get("name") == "keystone"


def tree_hashes(directory: Path) -> dict[str, str]:
    return {
        p.relative_to(directory).as_posix(): sha256(p.read_bytes())
        for p in sorted(directory.rglob("*"))
        if p.is_file() and p.name != COPY_MARKER
    }


def state(path: Path) -> str:
    if path.is_symlink():
        return CLEAN if link_is_ours(path) else FOREIGN
    if not path.exists():
        return ABSENT
    if path.is_dir():
        marker = path / COPY_MARKER
        if not marker.is_file():
            return FOREIGN
        try:
            recorded = json.loads(marker.read_text(encoding="utf-8"))["files"]
        except (OSError, ValueError, KeyError, TypeError):
            return MODIFIED
        return CLEAN if tree_hashes(path) == recorded else MODIFIED
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return FOREIGN
    found = MARKER_LINE.search(text)
    if not found:
        return FOREIGN
    rest = text[: found.start()] + text[found.end() :]
    return CLEAN if sha256(rest.encode("utf-8")) == found.group(1) else MODIFIED


def remove(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def plan(harness: str, scope: str, root: Path) -> list[tuple[Path, object]]:
    """(destination, source Path for a skill dir | str content for a file)."""
    where = targets(harness, scope, root)
    items: list[tuple[Path, object]] = [
        (where["skills"] / d.name, d)
        for d in sorted((ROOT / "skills").iterdir())
        if (d / "SKILL.md").exists()
    ]
    commands, agents = rendered(harness)
    if where["commands"]:
        items += [(where["commands"] / name, text) for name, text in commands.items()]
    if where["agents"]:
        items += [(where["agents"] / name, text) for name, text in agents.items()]
    return items


def install_copy(source: Path, dest: Path) -> None:
    shutil.copytree(source, dest)
    record = {
        "installed_by": "Keystone scripts/install_agents.py",
        "files": tree_hashes(dest),
    }
    (dest / COPY_MARKER).write_text(
        json.dumps(record, indent=1) + "\n", encoding="utf-8"
    )


def apply(
    items: list[tuple[Path, object]], copy: bool, dry_run: bool
) -> tuple[int, list[str], list[str]]:
    written, foreign, modified = 0, [], []
    for dest, source in items:
        current = state(dest)
        if current == FOREIGN:
            foreign.append(str(dest))
            continue
        if current == MODIFIED:
            modified.append(str(dest))
            continue
        if dry_run:
            written += 1
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if current == CLEAN:
            remove(dest)
        if isinstance(source, Path):
            if copy or os.name == "nt":
                install_copy(source, dest)
            else:
                dest.symlink_to(source, target_is_directory=True)
        else:
            dest.write_text(str(source), encoding="utf-8")
        written += 1
    return written, foreign, modified


def report(foreign: list[str], modified: list[str]) -> None:
    for path in foreign:
        print(f"  kept yours: {path}")
    for path in modified:
        print(f"  kept, edited since install: {path} (delete it to reinstall)")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("harness", choices=HARNESSES)
    parser.add_argument("--scope", choices=("project", "user"), default="project")
    parser.add_argument("--root", default=".", help="project directory (default: .)")
    parser.add_argument(
        "--copy", action="store_true", help="copy skills instead of symlinking"
    )
    parser.add_argument(
        "--contract",
        action="store_true",
        help="also add AGENTS.md if the project has none",
    )
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    items = plan(args.harness, args.scope, root)

    if args.uninstall:
        gone, modified = [], []
        for dest, _ in items:
            current = state(dest)
            if current == CLEAN:
                gone.append(dest)
            elif current == MODIFIED:
                modified.append(str(dest))
        for dest in gone:
            if not args.dry_run:
                remove(dest)
        verb = "would remove" if args.dry_run else "removed"
        print(f"{args.harness}: {verb} {len(gone)} Keystone item(s)")
        report([], modified)
        return 0

    written, foreign, modified = apply(items, args.copy, args.dry_run)
    verb = "would install" if args.dry_run else "installed"
    print(f"{args.harness}: {verb} {written} item(s) ({args.scope} scope)")
    report(foreign, modified)
    if args.contract:
        contract = root / "AGENTS.md"
        if contract.exists():
            print(
                "  AGENTS.md exists: merge Keystone's operating contract into it by hand"
            )
        elif not args.dry_run:
            shutil.copy2(ROOT / "AGENTS.md", contract)
            print("  added AGENTS.md (Keystone's operating contract)")
    if args.scope == "project" and written:
        print(
            f"  note: installed items point at {ROOT.as_posix()} on this machine;"
            " keep them out of version control (see docs/multi-agent-setup.md)"
        )
    if args.harness == "copilot" and args.scope == "user":
        print(
            "  Copilot prompt files and agents are installed per project; rerun without --scope user"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
