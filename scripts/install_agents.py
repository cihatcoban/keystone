#!/usr/bin/env python3
"""Install Keystone into Cursor, opencode or GitHub Copilot.

Claude Code, Gemini CLI and Codex load Keystone as a plugin or extension
(docs/multi-agent-setup.md). These three read the shared Agent Skills
location instead, and this script puts Keystone there, plus the commands and
subagents each one supports:

| Harness  | Skills                    | Commands                        | Subagents          |
|----------|---------------------------|---------------------------------|--------------------|
| cursor   | .agents/skills/           | — (skills are /-invocable)      | —                  |
| opencode | .agents/skills/           | .opencode/commands/keystone-*.md | .opencode/agents/ |
| copilot  | .agents/skills/           | .github/prompts/keystone-*.prompt.md (project) | .github/agents/ (project) |

    python3 install_agents.py opencode                 # this project
    python3 install_agents.py opencode --scope user    # every project
    python3 install_agents.py copilot --contract       # also AGENTS.md, if absent
    python3 install_agents.py cursor --uninstall
    python3 install_agents.py copilot --dry-run

Skills are symlinked so `git pull` in Keystone updates them (`--copy` to copy).
Generated files carry a marker; --uninstall removes only what carries it, and
nothing the user wrote is ever overwritten.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import build_adapters  # noqa: E402 — must follow the sys.path insert; scripts/ is not a package

MARKER = "<!-- GENERATED by Keystone scripts/install_agents.py; reinstall to update -->"
COPY_MARKER = ".keystone-installed"
HARNESSES = ("cursor", "opencode", "copilot")
PREAMBLE = (
    "This is a Keystone command. Activate every Keystone skill named below "
    "before acting, and follow the operating contract in AGENTS.md.\n\n"
)


def targets(harness: str, scope: str, root: Path) -> dict[str, Path | None]:
    home = Path.home()
    base = root if scope == "project" else home
    out: dict[str, Path | None] = {
        "skills": base / ".agents" / "skills",
        "commands": None,
        "agents": None,
    }
    if harness == "opencode":
        conf = (
            root / ".opencode" if scope == "project" else home / ".config" / "opencode"
        )
        out["commands"], out["agents"] = conf / "commands", conf / "agents"
    elif harness == "copilot" and scope == "project":
        out["commands"], out["agents"] = (
            root / ".github" / "prompts",
            root / ".github" / "agents",
        )
    return out


def adapt(body: str, arguments: str) -> str:
    text = body.replace("$ARGUMENTS", arguments).replace("`CLAUDE.md`", "`AGENTS.md`")
    return PREAMBLE + text.replace("${CLAUDE_PLUGIN_ROOT}", ROOT.as_posix())


def frontmatter(fields: dict[str, str]) -> str:
    # JSON strings are valid YAML scalars and survive ': ' inside a description.
    lines = [f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in fields.items()]
    return "---\n" + "\n".join(lines) + "\n---\n" + MARKER + "\n\n"


def rendered(harness: str) -> tuple[dict[str, str], dict[str, str]]:
    """({command file name: content}, {agent file name: content})."""
    commands, agents = {}, {}
    for src in sorted((ROOT / "commands").glob("*.md")):
        desc, body = build_adapters.parse_command(src)
        if harness == "opencode":
            commands[f"keystone-{src.stem}.md"] = frontmatter(
                {"description": desc}
            ) + adapt(body, "$ARGUMENTS")
        elif harness == "copilot":
            text = adapt(body, "the text typed after the command")
            commands[f"keystone-{src.stem}.prompt.md"] = (
                frontmatter({"description": desc}) + text
            )
    for src in sorted((ROOT / "agents").glob("*.md")):
        text = src.read_text(encoding="utf-8")
        _, meta, body = text.split("---\n", 2)
        fields = dict(
            line.split(": ", 1) for line in meta.strip().splitlines() if ": " in line
        )
        if harness == "opencode":
            agents[src.name] = (
                frontmatter({"description": fields["description"], "mode": "subagent"})
                + body.lstrip()
            )
        elif harness == "copilot":
            agents[src.name] = (
                frontmatter(
                    {"name": fields["name"], "description": fields["description"]}
                )
                + body.lstrip()
            )
    return commands, agents


def ours(path: Path) -> bool:
    if path.is_symlink():
        try:
            return path.resolve().is_relative_to((ROOT / "skills").resolve())
        except OSError:
            return False
    if path.is_dir():
        return (path / COPY_MARKER).exists()
    try:
        return MARKER in path.read_text(encoding="utf-8", errors="replace")[:2000]
    except OSError:
        return False


def remove(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def plan(harness: str, scope: str, root: Path) -> list[tuple[Path, object]]:
    """(destination, source Path for a skill dir | str content for a file)."""
    where = targets(harness, scope, root)
    items: list[tuple[Path, object]] = [
        (where["skills"] / d.name, d)
        for d in sorted((ROOT / "skills").iterdir())
        if (d / "SKILL.md").exists()
    ]
    commands, agents = rendered(harness)
    if where["commands"]:
        items += [(where["commands"] / name, text) for name, text in commands.items()]
    if where["agents"]:
        items += [(where["agents"] / name, text) for name, text in agents.items()]
    return items


def apply(
    items: list[tuple[Path, object]], copy: bool, dry_run: bool
) -> tuple[int, list[str]]:
    written, skipped = 0, []
    for dest, source in items:
        if (dest.exists() or dest.is_symlink()) and not ours(dest):
            skipped.append(str(dest))
            continue
        if dry_run:
            written += 1
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists() or dest.is_symlink():
            remove(dest)
        if isinstance(source, Path):
            if copy or os.name == "nt":
                shutil.copytree(source, dest)
                (dest / COPY_MARKER).write_text(
                    "installed by Keystone scripts/install_agents.py\n"
                )
            else:
                dest.symlink_to(source, target_is_directory=True)
        else:
            dest.write_text(str(source), encoding="utf-8")
        written += 1
    return written, skipped


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("harness", choices=HARNESSES)
    parser.add_argument("--scope", choices=("project", "user"), default="project")
    parser.add_argument("--root", default=".", help="project directory (default: .)")
    parser.add_argument(
        "--copy", action="store_true", help="copy skills instead of symlinking"
    )
    parser.add_argument(
        "--contract",
        action="store_true",
        help="also add AGENTS.md if the project has none",
    )
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    items = plan(args.harness, args.scope, root)

    if args.uninstall:
        gone = [
            dest
            for dest, _ in items
            if (dest.exists() or dest.is_symlink()) and ours(dest)
        ]
        for dest in gone:
            if not args.dry_run:
                remove(dest)
        print(f"{args.harness}: removed {len(gone)} Keystone item(s)")
        return 0

    written, skipped = apply(items, args.copy, args.dry_run)
    verb = "would install" if args.dry_run else "installed"
    print(f"{args.harness}: {verb} {written} item(s) ({args.scope} scope)")
    for path in skipped:
        print(f"  kept yours: {path}")
    if args.contract:
        contract = root / "AGENTS.md"
        if contract.exists():
            print(
                "  AGENTS.md exists: merge Keystone's operating contract into it by hand"
            )
        elif not args.dry_run:
            shutil.copy2(ROOT / "AGENTS.md", contract)
            print("  added AGENTS.md (Keystone's operating contract)")
    if args.harness == "copilot" and args.scope == "user":
        print(
            "  Copilot prompt files and agents are installed per project; rerun without --scope user"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
