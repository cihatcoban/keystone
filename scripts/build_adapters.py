#!/usr/bin/env python3
"""Generate per-agent adapters from the single source of truth.

Source (hand-written, reviewed):
    commands/*.md         Claude Code slash commands (frontmatter + body)
    skills/*/SKILL.md     read natively by Claude Code, Gemini CLI and Codex
    agents/*.md           read natively by Claude Code and Gemini CLI

    hooks/registry.json   hook IDs, triggers and per-harness events (ADR-001)

Generated (never edit by hand):
    commands/keystone/*.toml   Gemini CLI custom commands -> /keystone:<name>
    hooks/claude-code.json     Claude Code hooks, wired by .claude-plugin/plugin.json
    hooks/codex.json           Codex hooks, wired by plugin.json (com.openai)
    hooks/gemini.json          Gemini CLI hooks, installed by scripts/install_hooks.py

Why generate instead of maintaining two copies: two hand-maintained versions of
one instruction drift apart within weeks, and the drift is silent. One source
plus a generator plus a CI check turns drift into a failing build.

Usage:
    python3 scripts/build_adapters.py           write adapters
    python3 scripts/build_adapters.py --check   exit 1 if adapters are stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT / "commands"
GEMINI_DIR = ROOT / "commands" / "keystone"
HOOKS_DIR = ROOT / "hooks"
REGISTRY = HOOKS_DIR / "registry.json"
HOOK_MANIFESTS = {
    "claude-code": HOOKS_DIR / "claude-code.json",
    "codex": HOOKS_DIR / "codex.json",
    "gemini": HOOKS_DIR / "gemini.json",
}
# How each harness names the plugin root inside a hook command. Gemini has no
# such variable outside an extension's own hooks file, so its manifest carries
# a placeholder that install_hooks.py replaces with an absolute path.
ROOT_REFERENCE = {
    "claude-code": '"${CLAUDE_PLUGIN_ROOT}"',
    "codex": '"${PLUGIN_ROOT}"',
    "gemini": '"<keystone-root>"',
}

HEADER = (
    "# GENERATED by scripts/build_adapters.py from commands/{name}.md\n"
    "# Do not edit. Change the .md source and run: make adapters\n\n"
)
GEMINI_EXTENSION_ROOT = (
    "$HOME/.gemini/extensions/keystone"  # $HOME expands in quotes; ~ does not
)
PREAMBLE = (
    "This is a Keystone command. Keystone skills are available to you by name; "
    "activate every skill named below before acting, and follow the operating "
    "contract in AGENTS.md.\n\n"
)


class SourceError(ValueError):
    pass


def parse_command(path: Path) -> tuple[str, str]:
    """Return (description, body) from a Claude Code command file."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not match:
        raise SourceError(f"{path.name}: missing frontmatter")
    frontmatter, body = match.groups()
    desc = re.search(r"^description:\s*(.+)$", frontmatter, re.M)
    if not desc:
        raise SourceError(f"{path.name}: frontmatter has no description")
    return desc.group(1).strip(), body.strip() + "\n"


def to_gemini_prompt(body: str) -> str:
    # Claude Code substitutes $ARGUMENTS; Gemini CLI substitutes {{args}}.
    prompt = body.replace("$ARGUMENTS", "{{args}}")
    # Gemini loads the contract via contextFileName = AGENTS.md (same content).
    prompt = prompt.replace("`CLAUDE.md`", "`AGENTS.md`")
    # Gemini has no plugin-root variable in commands; extensions install here.
    prompt = prompt.replace("${CLAUDE_PLUGIN_ROOT}", GEMINI_EXTENSION_ROOT)
    return PREAMBLE + prompt


def toml_string(value: str) -> str:
    """Encode as a TOML literal string when safe, else a basic string."""
    if "\n" not in value and "'" not in value:
        return f"'{value}'"
    if "'''" not in value:
        # Multi-line literal string: no escape processing, what you see is sent.
        return "'''\n" + value + "'''"
    escaped = value.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + escaped + '"""'


def render_gemini(name: str, description: str, body: str) -> str:
    return (
        HEADER.format(name=name)
        + f"description = {toml_string(description)}\n\n"
        + f"prompt = {toml_string(to_gemini_prompt(body))}\n"
    )


def load_registry(path: Path = REGISTRY) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SourceError(f"{path.name}: unreadable ({exc})") from exc
    for key in ("triggers", "hooks"):
        if key not in data:
            raise SourceError(f"{path.name}: missing '{key}'")
    return data


def render_hook_manifest(harness: str, registry: dict) -> str:
    """One harness's hook manifest: a matcher group per trigger in use."""
    used = {t for hook in registry["hooks"] for t in hook["trigger"]}
    events: dict[str, list[dict]] = {}
    for trigger, spec in registry["triggers"].items():
        if trigger not in used:
            continue
        if harness not in spec:
            raise SourceError(
                f"registry.json: trigger '{trigger}' has no '{harness}' entry"
            )
        wiring = spec[harness]
        command = (
            f"sh {ROOT_REFERENCE[harness]}/hooks/run.sh "
            f"--harness {harness} --trigger {trigger}"
        )
        handler: dict = {"type": "command", "command": command}
        if harness == "gemini":
            handler = {"name": f"keystone-{trigger}", **handler}
            handler["timeout"] = spec["timeout_s"] * 1000  # Gemini counts milliseconds
        else:
            handler["timeout"] = spec["timeout_s"]
        group: dict = {}
        if "matcher" in wiring:
            group["matcher"] = wiring["matcher"]
        group["hooks"] = [handler]
        events.setdefault(wiring["event"], []).append(group)
    manifest = {
        "description": (
            f"Keystone hooks for {harness}. GENERATED by scripts/build_adapters.py "
            "from hooks/registry.json; do not edit. See docs/hooks.md."
        ),
        "hooks": events,
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def expected_outputs() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for src in sorted(SOURCE_DIR.glob("*.md")):
        description, body = parse_command(src)
        outputs[GEMINI_DIR / f"{src.stem}.toml"] = render_gemini(
            src.stem, description, body
        )
    registry = load_registry()
    for harness, path in HOOK_MANIFESTS.items():
        outputs[path] = render_hook_manifest(harness, registry)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if adapters are stale"
    )
    args = parser.parse_args()

    try:
        expected = expected_outputs()
    except SourceError as exc:
        print(f"ERROR  {exc}")
        return 1

    existing = set(GEMINI_DIR.glob("*.toml")) if GEMINI_DIR.is_dir() else set()
    stale = [
        p
        for p, c in expected.items()
        if not p.exists() or p.read_text(encoding="utf-8") != c
    ]
    orphans = sorted(existing - set(expected))

    if args.check:
        for p in stale:
            print(f"STALE  {p.relative_to(ROOT)} (run: make adapters)")
        for p in orphans:
            print(f"ORPHAN {p.relative_to(ROOT)} has no commands/*.md source")
        print(
            f"adapters: {len(expected)} expected · {len(stale)} stale · {len(orphans)} orphaned"
        )
        return 1 if stale or orphans else 0

    GEMINI_DIR.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(expected[path], encoding="utf-8")
    for path in orphans:
        path.unlink()
    print(
        f"adapters: wrote {len(stale)}, removed {len(orphans)}, {len(expected)} total"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
